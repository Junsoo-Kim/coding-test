SELECT CAR_ID, C.CAR_TYPE, DAILY_FEE * 30 * DISCOUNT_RATE AS FEE
FROM CAR_RENTAL_COMPANY_CAR AS C JOIN (
    SELECT CAR_TYPE, (100 - DISCOUNT_RATE) / 100 AS DISCOUNT_RATE
    FROM CAR_RENTAL_COMPANY_DISCOUNT_PLAN
    WHERE DURATION_TYPE = '30일 이상'
) AS D ON C.CAR_TYPE = D.CAR_TYPE
WHERE 
C.CAR_TYPE IN ('세단', 'SUV')
AND CAR_ID NOT IN (
    SELECT CAR_ID
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    WHERE (START_DATE < '2022-11-01' AND END_DATE > '2022-11-30')
    OR (START_DATE >= '2022-11-01' AND START_DATE <= '2022-11-30')
    OR (END_DATE >= '2022-11-01' AND END_DATE <= '2022-11-30')
)
AND (DAILY_FEE * 30 * DISCOUNT_RATE >= 500000 AND DAILY_FEE * 30 * DISCOUNT_RATE < 2000000)
ORDER BY FEE DESC, CAR_TYPE ASC, CAR_ID DESC